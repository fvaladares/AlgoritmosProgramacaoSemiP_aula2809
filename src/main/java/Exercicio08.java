//Crie um programa que imprima a sequência
// de números entre 200 e 100, em ordem decrescente.

public class Exercicio08 {
    public static void main(String[] args) {

        System.out.println("Impressão em ordem decrescente");

        for (int i = 199; i > 100; i = i - 1) {
            System.out.println(i);
        }
    }
}
